#!/usr/bin/env bash
# به‌روزرسانی توضیحات فارسی Release v2.14.2 — رفع «مدل جمنای پیدا نشد» + قسط‌بندی وام
set -euo pipefail

TAG="v2.14.2"
REPO="021hk/modiriat-hesab"
TOKEN=$(git config remote.origin.url | grep -oP '(?<=://)[^@]+(?=@)' | cut -d: -f2)

BODY=$(cat <<'EOF'
## حساب‌یار نسخه ۲.۱۴.۲ — رفع خطای «مدل جمنای پیدا نشد» + قسط‌بندی خودکار وام

### 🤖 رفع مشکل دستیار هوشمند (Gemini)
- اگر پیام «مدل پیدا نشد» می‌دیدید، حالا برنامه **خودش مدل‌های فعال کلید شما را از گوگل می‌خواند** و بهترین مدل را انتخاب و روی دستگاه ذخیره می‌کند — دیگر با بازنشسته شدن مدل‌ها دستیار از کار نمی‌افتد
- دکمهٔ جدید **«تست اتصال»** در تنظیمات: کلید و مدل را همان‌جا آزمایش می‌کند و نتیجه را با پیام فارسی روشن نشان می‌دهد (کلید نامعتبر / اینترنت و VPN / سقف درخواست / مدل فعال)
- نام مدل فعال کنونی در تنظیمات نمایش داده می‌شود

### ⚙️ تنظیمات دستیار
- کلید **فعال/غیرفعال کردن دستیار هوشمند** به تب تنظیمات منتقل شد — خاموش کنید تا گوی سبز شناور نشان داده نشود
- تنظیم «خواندن پاسخ با صدا» هم در تنظیمات اضافه شد (داخل پنل گفتگو هم هست)

### 🏦 قسط‌بندی وام (جدید)
- در تب «اقساط و چک‌ها» دکمهٔ **«قسط‌بندی وام»**: اصل وام، **تعداد اقساط** (مثلاً ۳۵)، نرخ سود سالانه و نوع نرخ را وارد کنید:
  - **نزولی** — وام بانکی (قسط اول بزرگ‌تر، کم‌کم کم می‌شود)
  - **ثابت** — همهٔ اقساط برابر
  - **سعودی** — قسط اول کوچک‌تر، کم‌کم زیاد می‌شود
- **پیش‌نمایش زندهٔ** جدول: قسط اول/آخر، کمترین/بیشترین، جمع سود و جمع پرداخت — قبل از ثبت
- **تاریخ سررسید خودکار**: همان روزِ ماهِ تاریخ اولین سررسید در تقویم شمسی (۱۵ مهر ← ۱۵ آبان ← ۱۵ آذر و…) و اگر روز در ماه نباشد به آخر آن ماه می‌رود
- هر قسط با عنوان «قسط ۳ از ۳۵» و نشان جدا ثبت می‌شود؛ **اعلان یادآور هر قسط** خودکار زمان‌بندی می‌شود
- دکمهٔ «حذف کل طرح» اقساط پرداخت‌نشده را حذف می‌کند و پرداخت‌شده‌ها بایگانی می‌مانند

### 🛠 موارد دیگر
- مجموع تست‌های خودکار: ۴۷۰ مورد سبز

---
### 📲 نصب
فایل APK را دانلود و روی نسخهٔ قبل نصب کنید؛ داده‌ها حفظ می‌شود.
EOF
)

RELEASE_ID=$(curl -s -H "Authorization: Bearer $TOKEN" "https://api.github.com/repos/$REPO/releases/tags/$TAG" | python3 -c "import sys,json;print(json.load(sys.stdin)['id'])")
echo "release id: $RELEASE_ID"

python3 - "$RELEASE_ID" "$BODY" <<'PY'
import json, sys, urllib.request
rid, body = sys.argv[1], sys.argv[2]
token = __import__("subprocess").check_output(
    ["bash", "-lc", "git config remote.origin.url | grep -oP '(?<=://)[^@]+(?=@)' | cut -d: -f2"],
    text=True).strip()
req = urllib.request.Request(
    f"https://api.github.com/repos/021hk/modiriat-hesab/releases/{rid}",
    data=json.dumps({"body": body}).encode(),
    headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"},
    method="PATCH")
with urllib.request.urlopen(req) as r:
    print("release body updated:", r.status)
PY

#!/bin/bash
# بروزرسانی توضیحات Release v2.8.0 به فارسی
set -e
cd /home/z/my-project
TOKEN=$(git config remote.origin.url | grep -oP '(?<=://)[^@]+(?=@)' | cut -d: -f2)
REPO="021hk/modiriat-hesab"
TAG="v2.8.0"

BODY=$(cat <<'EOF'
## حساب‌یار نسخه ۲.۸.۰ — طبق درخواست‌های شما

### ۱) انتخاب شماره پیامک، تمام‌صفحه شد
- پنجره «شماره‌های روی گوشی» حالا در موبایل تمام‌صفحه باز می‌شود و نوشته‌ها دیگر روی هم نمی‌افتند
- فرم افزودن/ویرایش حساب هم در صفحه‌های کوچک قابل اسکرول است

### ۲) ویرایش تراکنش — داده‌های قبلی نشان داده می‌شود
- باگ: وقتی یک ردیف تراکنش را ویرایش می‌کردید، فرم خالی بود و داده‌های قبلی نمی‌آمد
- حالا مبلغ، بابت، دسته، حساب و تاریخِ همان تراکنش در فرم پیش‌پر می‌شود

### ۳) دسته‌بندی با زیرشاخه — تا ۳ سطح
- هر دسته هزینه/درآمد می‌تواند تا ۳ زیرشاخه داشته باشد (مثلاً خواربار ← میوه ← تابستانه)
- روی هر دسته دکمه ↵ برای ساخت زیرشاخه
- کلید «زیرشاخه فعال»: اگر برای دسته‌ای خاموش کنید، نمی‌توانید زیر آن زیرشاخه بسازید
- در فرم تراکنش و فیلترها، زیرشاخه‌ها با تودرتو نمایش داده می‌شوند

### ۴) تاریخ تراکنش به‌صورت جلالی با ساعت
- انتخابگر جدید: اول سال، بعد ماه، بعد روز، بعد ساعت
- تراکنش‌ها حالا با ساعت دقیق مرتب می‌شوند (سال ← ماه ← روز ← ساعت)
- تقویم کاملاً جلالی است (فروردین تا اسفند، با کبیسه درست)

### ۵) داشبورد درست شد
- باگ «همه هزینه‌ها بدون دسته»: تفکیک دسته‌ها حالا درست نشان داده می‌شود
- باگ عدد منفی/غلط: موجودی کل حساب‌ها حالا از موجودی واقعی بانک (مانده پیامک) خوانده می‌شود
- «درآمد/هزینه این ماه» حالا با تقویم جلالی حساب می‌شود (قبلاً ماه میلادی بود و آمار نمی‌خواند)

### نصب
1. فایل APK زیر را دانلود و نصب کنید (داده‌ها حفظ می‌شوند)
2. تب «دسته‌بندی» را باز کنید و برای دسته‌هایتان زیرشاخه بسازید
3. داشبورد را ببینید — آمار این ماه جلالی است

**۱۳۶ تست خودکار — تقویم جلالی با تست رفت‌وبرگشت ۴۰۰ ساله تأیید شده**
EOF
)

RELEASE_ID=$(curl -s -H "Authorization: token $TOKEN" "https://api.github.com/repos/$REPO/releases/tags/$TAG" | grep -oP '(?<="id": )\d+' | head -1)
echo "release id: $RELEASE_ID"
curl -s -X PATCH \
  -H "Authorization: token $TOKEN" \
  -H "Content-Type: application/json" \
  -d "$(python3 -c "import json,sys; print(json.dumps({'body': sys.stdin.read()}))" <<< "$BODY")" \
  "https://api.github.com/repos/$REPO/releases/$RELEASE_ID" > /dev/null
echo "release notes updated"

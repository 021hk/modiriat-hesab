#!/usr/bin/env python3
# یادداشت انتشار فارسی برای v2.17.0 — به‌روزرسانی بدنهٔ رلیز از طریق GitHub API
import json
import os
import urllib.request

TOKEN = os.environ["GH_TOKEN"]

RELEASE_ID = 443591884
BODY = """حساب‌یار ۲.۱۷.۰ — دستیار داده‌آگاه + سازگاری با هر پروکسی

🤖 دستیار هوشمند حالا روی دادهٔ واقعی شما حساب می‌کند
• سؤال‌های آماری مثل «مجموع هزینه‌های یه ماه اخیر زیر مبلغ ۲۰۰ تومن چقدره؟» یا «چند تا زیر ۳۰۰ تومن داشتیم؟» حالا جواب دقیق می‌گیرند — مدل دیگر حدس نمی‌زند؛ برنامه روی تراکنش‌های خودِ دستگاه محاسبه می‌کند و نتیجهٔ واقعی را به مدل می‌دهد تا پاسخ طبیعی بدهد.
• انواع محاسبه: مجموع، تعداد، میانگین، بیشترین، کمترین و فهرست نمونه‌ها — با فیلتر مبلغ (زیرِ/بالاتر از/دقیقاً/بین دو مبلغ)، دورهٔ شمسی (این ماه، ماه گذشته، ۷/۳۰/۹۰ روز اخیر، امسال)، دسته، حساب بانکی و جستجو در «بابت».
• ماه‌ها با تقویم جلالی دقیق محاسبه می‌شوند — «ماه گذشته» یعنی واقعاً ماه شمسیِ قبل، نه ۳۰ روز تقریبی.
• اگر اتصال وسط کار قطع شود یا سهمیه تمام شود، همان لحظه جوابِ قطعیِ محلی (مجموع و تعداد) نمایش داده می‌شود — دستیار حتی بدون پاسخ مدل عدد درست می‌دهد.
• تفسیر «تومن»: اگر با معنی معمول نتیجه صفر شد، دستیار شفاف می‌گوید چه تفسیری از مبلغ گرفته و تفسیر دیگر («تومن» یعنی هزار تومان) را هم بررسی می‌کند.
• موجودی حساب‌ها، بدهی‌ها و اقساط همان‌طور که قبل از زمینهٔ برنامه جواب داده می‌شوند.

🌍 پروکسی شخصی — حالا هر پروکسی‌ای کار می‌کند
• کلید API علاوه بر هدر، به‌صورت ?key= هم در آدرس فرستاده می‌شود؛ پس پروکسی‌هایی که هدرها را پاس نمی‌دهند (بعضی Workerهای آماده) هم جواب می‌دهند.
• هر پروکسی‌ای که فقط مسیر /v1beta/… گوگل را همان برساند کافی است — Cloudflare Worker، nginx یا سرور شخصی خودتان؛ آدرس را در تنظیمات ← «پروکسی شخصی» بگذارید.

توصیه: بعد از نصب، در تنظیمات دکمهٔ «تست اتصال» را بزنید و بعد از دستیار بپرسید: «مجموع هزینه‌های ماه گذشته چقدره؟» یا «چند تا هزینه زیر ۵۰۰ هزار تومان داشتیم؟"""

req = urllib.request.Request(
    f"https://api.github.com/repos/021hk/modiriat-hesab/releases/{RELEASE_ID}",
    data=json.dumps({"body": BODY}).encode("utf-8"),
    headers={
        "Authorization": f"token {TOKEN}",
        "Content-Type": "application/json",
        "User-Agent": "hesab-yar-release",
    },
    method="PATCH",
)
with urllib.request.urlopen(req) as r:
    out = json.load(r)
print("PATCHed release:", out["tag_name"], "| new body length:", len(out["body"]))

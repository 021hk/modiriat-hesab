#!/usr/bin/env python3
# یادداشت انتشار فارسی برای v2.16.0 — به‌روزرسانی بدنهٔ رلیز از طریق GitHub API
import json
import os
import urllib.request

TOKEN = os.environ["GH_TOKEN"]

RELEASE_ID = 442310682
BODY = """حساب‌یار ۲.۱۶.۰ — پیام بانک (بلوبانک) + رنگ حساب + رفع کامل اتصال هوش مصنوعی

💙 ثبت پیام بلوبانک — واریز و برداشت خودکار
• پیام یا نوتیفیکیشن بلوبانک را کپی کنید و در تب «حساب‌ها» ← «ورود پیام بانکی» بچسبانید؛ یا روی پیام Share بزنید و «حساب‌یار» را انتخاب کنید — پیام همین‌جا باز می‌شود.
• نوع تراکنش (واریز/برداشت)، مبلغ، نام بانک، «بابت» و موجودی جدید همه خودکار تشخیص داده می‌شوند — نمونه: «۲۲۰,۰۰۰ ریال بابت خرید شارژ از حساب شما کم شد» → برداشت ۲۲۰,۰۰۰ ریال با بابتِ «خرید شارژ».
• تاریخ و ساعت شمسی داخل پیام (مثل ۱۴۰۵.۰۸.۲۱ — ۰۲:۴۲) هم خوانده می‌شود و به خود تراکنش اعمال می‌شود؛ ارقام فارسی و انگلیسی هر دو پذیرفته می‌شود.
• پیام اول در «پیش‌نمایش تشخیص» نتیجه را نشان می‌دهد، بعد در صف بررسی می‌رود و با یک لمس به حساب بانکی شما وصل می‌شود.
• پشتیبانی از واریز، برداشت و واریز سود بانکی بلو — پیامک‌های بانک‌های دیگر هم همان‌طور که قبل کار می‌کند.
• رفع اشکال: دکمهٔ «پیش‌نمایش تشخیص» که مدتی کار نمی‌کرد، حالا درست جواب می‌دهد.

🎨 رنگ حساب — کل کارت با رنگ خودتان
• رنگی که برای حساب انتخاب می‌کنید حالا کل کارت همان حساب را رنگ می‌گیرد: پس‌زمینهٔ ملایم، خط دور و نوار بالای کارت — هم در حالت روشن هم تاریک.

🤖 رفع کامل اتصال Gemini (بر اساس لاگ واقعی شما)
• خطای ۴۲۹ (اتمام سهمیه) دیگر همه‌چیز را نمی‌بندد — سهمیهٔ هر مدل جداست؛ برنامه خودش مدل‌های دیگر را امتحان می‌کند تا یکی جواب بدهد.
• پیام خطاها فارسی و دقیق شد: «سهمیهٔ رایگان تمام شده» جدا از «سرعت درخواست زیاد» — و راه‌حل (کلید دوم رایگان از aistudio.google.com/apikey) داخل همان پیام هست.
• زمان انتظار پاسخ از ۳۰ ثانیه به ۴۵ ثانیه رسید — مدل‌های جدید گاهی دیرتر جواب می‌دهند و قبلاً وسط کار قطع می‌شد.
• اگر نسخهٔ قبلی مدلِ بازنشسته (مثل gemini-2.5-flash) را کش کرده باشد، خودکار پاک می‌شود و مدل فعال پیدا می‌شود.

🛡 امنیت — برنامه خطرناک شناخته نمی‌شود
• مجوزهای حساس پیامک (READ_SMS و RECEIVE_SMS) به‌طور کامل حذف شدند — برنامه حالا فقط مجوز اینترنت دارد و Play Protect دیگر دلیل خطرناک بودن نمی‌بیند.
• خواندن پیام بانک حالا فقط با Share کردن یا چسباندن متن انجام می‌شود — هیچ داده‌ای بدون اطلاع شما خوانده یا ارسال نمی‌شود.

🏦 بانک‌های بیشتر
• بلوبانک، خاورمیانه، مهر ایران، ایران زمین، حکمت ایرانیان، گردشگری، کوثر و مهر اقتصاد به فهرست بانک‌ها اضافه شدند.

توصیه: بعد از نصب، یک حساب برای بلوبانک بسازید (بانک «بلوبانک»)، بعد پیام واریز/برداشت بلو را Share کنید تا خودکار ثبت شود. برای دستیار هوشمند هم «تست اتصال» را بزنید."""

req = urllib.request.Request(
    f"https://api.github.com/repos/021hk/modiriat-hesab/releases/{RELEASE_ID}",
    data=json.dumps({"body": BODY}).encode("utf-8"),
    headers={
        "Authorization": f"token {TOKEN}",
        "Content-Type": "application/json",
        "User-Agent": "hesab-yar-release",
    },
    method="PATCH",
)
with urllib.request.urlopen(req) as r:
    out = json.load(r)
print("PATCHed release:", out["tag_name"], "| new body length:", len(out["body"]))

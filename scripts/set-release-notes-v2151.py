#!/usr/bin/env python3
# یادداشت انتشار فارسی برای v2.15.1 — به‌روزرسانی بدنهٔ رلیز از طریق GitHub API
import json
import urllib.request

TOKEN = None  # از متغیر محیطی خوانده می‌شود
import os
TOKEN = os.environ["GH_TOKEN"]

RELEASE_ID = 433926550
BODY = """حساب‌یار ۲.۱۵.۱ — لاگ تشخیصی اتصال + سازگاری با اسکن امنیتی گوگل‌پلی

🔌 لاگ اتصال (تشخیصی) — بلاخره ببینیم چرا وصل نمی‌شود
• در تنظیمات ← دستیار هوشمند، بخش جدید «لاگ اتصال (تشخیصی)» اضافه شد.
• هر گام اتصال به Gemini ثبت می‌شود: آزمون دسترسی به گوگل، گرفتن فهرست مدل‌ها، هر تلاش فراخوانی، تایم‌اوت‌ها، تلاش‌های مجدد و گردش بین چند کلید.
• خطاهای HTTP با کد وضعیت و متن واقعی سرور گوگل (تا ۲۰۰ نویسه) ثبت می‌شوند — مثلاً «API key not valid» یا پیام تحریم منطقه‌ای، دقیقاً معلوم می‌شود کجا و چرا شکسته.
• مدت هر درخواست (میلی‌ثانیه) و میزبان (مستقیم به گوگل یا پروکسی شخصی شما) هم نوشته می‌شود.
• دکمهٔ «کپی لاگ»: کل گزارش را به‌شکل متن کپی می‌کند تا برای بررسی بفرستید؛ دکمهٔ «پاک کردن» هم هست.
• لاگ فقط روی خود دستگاه ذخیره می‌شود و کلیدهای API همیشه ماسک می‌شوند (۴ حرف اول + ۴ حرف آخر).

🛡 سازگاری با اسکن امنیتی گوگل‌پلی
• پشتیبان‌گیری ابری اندروید برای دادهٔ حساس مالی خاموش شد (allowBackup=false).
• ترافیک رمزنشده (http) به‌طور صریح مسدود شد (usesCleartextTraffic=false).
• آدرس پروکسی فقط https پذیرفته می‌شود — اگر http وارد کنید، هشدار فارسی نشان داده می‌شود.
• کلید API هرگز کامل در لاگ یا گزارش‌ها نمی‌آید.

✨ از نسخهٔ قبل (۲.۱۵.۰)
• تم کهکشانی یکپارچه: شب/روز خودکار — تیره با ستاره‌های روشن یا سفید با ستاره‌های رنگی.
• مشکی کامل خودکار روی حالت تاریک می‌رود.
• پروکسی شخصی (مثل Cloudflare Worker خودتان) برای عبور از محدودیت منطقه‌ای گوگل.
• چند کلید Gemini با گردش خودکار روی خطا.

توصیه: بعد از نصب، در تنظیمات «تست اتصال» را بزنید، بعد «لاگ اتصال» را باز کنید و «کپی لاگ» را بفرستید تا علت دقیق قطعی مشخص شود."""

req = urllib.request.Request(
    f"https://api.github.com/repos/021hk/modiriat-hesab/releases/{RELEASE_ID}",
    data=json.dumps({"body": BODY}).encode("utf-8"),
    headers={
        "Authorization": f"token {TOKEN}",
        "Content-Type": "application/json",
        "User-Agent": "hesab-yar-release",
    },
    method="PATCH",
)
with urllib.request.urlopen(req) as r:
    out = json.load(r)
print("PATCHed release:", out["tag_name"], "| new body length:", len(out["body"]))

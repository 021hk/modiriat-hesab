req = urllib.request.Request(
    f"https://api.github.com/repos/021hk/modiriat-hesab/releases/{RELEASE_ID}",
    data=json.dumps({"body": BODY}).encode("utf-8"),
    headers={"Authorization": f"token {TOKEN}", "Content-Type": "application/json", "User-Agent": "hesab-yar-release"},
    method="PATCH",
)
with urllib.request.urlopen(req) as r:
    out = json.load(r)
print("PATCHed release:", out["tag_name"], "| body length:", len(out["body"]))

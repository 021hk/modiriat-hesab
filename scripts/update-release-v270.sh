#!/bin/bash
# بروزرسانی توضیحات Release v2.7.0 به فارسی
set -e
cd /home/z/my-project
TOKEN=$(git config remote.origin.url | grep -oP '(?<=://)[^@]+(?=@)' | cut -d: -f2)
REPO="021hk/modiriat-hesab"
TAG="v2.7.0"

BODY=$(cat <<'EOF'
## حساب‌یار نسخه ۲.۷.۰ — موجودی بانکی از پیامک + بررسی خودکار همه‌جا

### موجودی حساب حالا از خود بانک پر می‌شود
- برنامه «مانده» را از پیامک بانک می‌خواند و **موجودی کارت حساب** را با عدد واقعی بانک به‌روز می‌کند (با نشان «موجودی بانک — از پیامک» و تاریخ آن)
- اگر پیامک تومانی باشد، خودکار به ریال تبدیل می‌شود (×۱۰)
- فقط «مانده» جدیدتر از آخرین مانده ثبت‌شده اعمال می‌شود؛ پیامک قدیمی موجودی را عقب نمی‌برد
- زیر عدد موجودی، «محاسبه‌شده از تراکنش‌ها» هم نمایش داده می‌شود

### بررسی پیامک‌ها دیگر محدود به یک تب نیست
- به‌محض باز شدن برنامه (هر تبی) پیامک‌های بانکی بررسی می‌شوند و اگر تراکنش جدیدی ثبت یا موجودی به‌روز شود، اعلان می‌بینید
- وقتی از برنامه خارج شده و برمی‌گردید، دوباره خودکار بررسی می‌شود
- پیامک تازه وقتی برنامه باز است، همان لحظه پردازش می‌شود

### گزارش شفاف بررسی — می‌بینید که واقعاً چه شد
- بعد از هر بررسی، کارت «خواندن خودکار پیامک بانکی» نشان می‌دهد: چند پیامک خوانده شد، چندی پیامک بانکی بود، چند تراکنش خودکار ثبت شد، چند مورد در صف است، موجودی چند حساب به‌روز شد، چند پیامک شماره ناهمسان یا حساب غریبه داشت
- اگر بررسی اصلاً انجام نشد (مثلاً شماره فرستنده تنظیم نشده یا دسترسی پیامک خاموش است) دلیلش همین‌جا نوشته می‌شود — دیگر فقط در پیام کوتاه گم نمی‌شود

### «چرا ثبت نمی‌شود؟» — تک‌تک پیامک‌ها را ببینید
- در «شماره‌های روی گوشی»، هر شماره دکمه‌ای دارد: «بررسی تک‌تک پیامک‌ها»
- ۱۰ پیامک آخر هر شماره با حکم برنامه نمایش داده می‌شود: خودکار ثبت می‌شود / در صف می‌آید / رد می‌شود (و چرا) + مبلغ، مانده، نوع و حساب تطبیق‌شده هر پیامک

### رفع باگ مهم
- پیامک‌هایی که فقط «مانده» داشتند (بدون واریز/برداشت)، مانده اشتباهی مبلغ تراکنش ثبت می‌شد — الان درست شد؛ این پیامک‌ها فقط موجودی را به‌روز می‌کنند

### نصب
1. فایل APK زیر را دانلود کنید
2. روی گوشی نصب کنید (نسخه قبلی را جایگزین می‌کند — داده‌ها حفظ می‌شوند)
3. یک بار تب «حساب و پیامک» را باز کنید و «بررسی الان» را بزنید تا گزارش جدید را ببینید

**۱۰۹ تست خودکار — بدون هیچ داده‌ای که از گوشی خارج شود**
EOF
)

RELEASE_ID=$(curl -s -H "Authorization: token $TOKEN" "https://api.github.com/repos/$REPO/releases/tags/$TAG" | grep -oP '(?<="id": )\d+' | head -1)
echo "release id: $RELEASE_ID"
curl -s -X PATCH \
  -H "Authorization: token $TOKEN" \
  -H "Content-Type: application/json" \
  -d "$(python3 -c "import json,sys; print(json.dumps({'body': sys.stdin.read()}))" <<< "$BODY")" \
  "https://api.github.com/repos/$REPO/releases/$RELEASE_ID" > /dev/null
echo "release notes updated"

#!/usr/bin/env bash
# به‌روزرسانی توضیحات فارسی Release v2.13.0 — فاصله از نوتش + دسته‌بندی خودکار با مبلغ + خروجی اکسل
set -euo pipefail

TAG="v2.13.0"
REPO="021hk/modiriat-hesab"
TOKEN=$(git config remote.origin.url | grep -oP '(?<=://)[^@]+(?=@)' | cut -d: -f2)

BODY=$(cat <<'EOF'
## حساب‌یار نسخه ۲.۱۳.۰ — فاصله از دوربین، دسته‌بندی خودکار با مبلغ، خروجی اکسل

### 📱 فاصله گرفتن از دوربین (نوتش) گوشی
- روی گوشی‌هایی که دوربین جلوی صفحه (نوتش) در بالای صفحه است، هدر برنامه حالا کمی پایین‌تر می‌نشیند و دیگر زیر دوربین نمی‌رود
- فقط روی همان گوشی‌ها فعال است — روی گوشی‌های بدون نوتش هیچ تغییری نمی‌بینید

### 🪄 دسته‌بندی خودکار با مبلغ (تنظیمات ← «دسته‌بندی خودکار با مبلغ»)
- قانون بسازید: **عدد مشخص** یا **محدوده** (از — تا) + دستهٔ مقصد، جدا برای **هزینه** و **درآمد** — هر چند تا که بخواهید
- هر تراکنش هزینه یا درآمدی که خودتان برایش دسته انتخاب نکرده باشید، اگر مبلغش با قانون بخواند، **خودکار** در دستهٔ همان قانون ثبت می‌شود
- در فرم تراکنش هم همان لحظه که مبلغ را می‌نویسید، دسته خودکار انتخاب و با نشان سبز اعلام می‌شود (اگر خودتان دسته بگذارید، انتخاب شما اولویت دارد)
- پیامک‌های بانکی هم شامل همین قوانین می‌شوند — هم ثبت خودکار و هم ثبت از صف؛ اگر پیامک بابت یک شخص باشد (بدهی/طلب) دسته اعمال نمی‌شود
- هر قانون را می‌توانید خاموش/روشن، ویرایش یا حذف کنید

### 📊 خروجی اکسل تراکنش‌ها
- دکمهٔ «خروجی اکسل» در تب تراکنش‌ها — همان لیستی که می‌بینید (با فیلترها و جستجوی فعال) به فایل اکسل (xlsx) تبدیل می‌شود
- ستون‌ها: تاریخ جلالی، ساعت، نوع (واریز/برداشت)، عنوان، بابت، مبلغ، دسته، حساب، شخص، منبع — شیت راست‌به‌چپ با سرستون بولد
- کاملاً آفلاین و بدون اینترنت ساخته می‌شود؛ فایل در اکسل، لیبره‌آفیس و گوگل‌شیت باز می‌شود

---
### 📲 نصب
فایل APK را دانلود و نصب کنید؛ روی نسخهٔ قبلی نصب می‌شود و داده‌های شما حفظ می‌شود.
EOF
)

RELEASE_ID=$(curl -s -H "Authorization: Bearer $TOKEN" "https://api.github.com/repos/$REPO/releases/tags/$TAG" | python3 -c "import sys,json;print(json.load(sys.stdin)['id'])")
echo "release id: $RELEASE_ID"

python3 - "$RELEASE_ID" "$BODY" <<'PY'
import json, sys, urllib.request
rid, body = sys.argv[1], sys.argv[2]
token = __import__("subprocess").check_output(
    ["git", "config", "remote.origin.url"], text=True
)
token = token.strip().split("//")[1].split("@")[0].split(":")[1]
req = urllib.request.Request(
    f"https://api.github.com/repos/021hk/modiriat-hesab/releases/{rid}",
    data=json.dumps({"body": body}).encode(),
    headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
    method="PATCH",
)
print(urllib.request.urlopen(req).status)
PY

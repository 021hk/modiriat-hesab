#!/usr/bin/env bash
# به‌روزرسانی توضیحات فارسی Release v2.14.0 — گوی هوشمند Gemini + اقساط و چک با اعلان + تفکیک چند حساب
set -euo pipefail

TAG="v2.14.0"
REPO="021hk/modiriat-hesab"
TOKEN=$(git config remote.origin.url | grep -oP '(?<=://)[^@]+(?=@)' | cut -d: -f2)

BODY=$(cat <<'EOF'
## حساب‌یار نسخه ۲.۱۴.۰ — گوی هوشمند، اقساط و چک با یادآور، تفکیک چند حساب

### ✨ گوی هوشمند (دستیار Gemini)
- گوی سبز سه‌بعدی شناور روی صفحه — با انگشت هر جا بخواهید جابه‌جایش کنید؛ جایش ذخیره می‌شود
- با لمسش باز می‌شود و **حالت گفتگو** دارد: دستور را **بنویسید یا بگویید** (میکروفون) 🎙
- نمونهٔ دستور: «مبالغ بین ۱۰۰ تا ۵۰۰ هزار تومان رو ببر تو هزینه‌های جاری» → خودش همه را دسته‌بندی می‌کند
- کارهایی که انجام می‌دهد: دسته‌بندی گروهی با مبلغ/محدوده، ساختن قانون دائمی دسته‌بندی خودکار، ثبت تراکنش، ثبت قسط/چک — و به سؤال‌های آماری (موجودی، خرج این ماه، بدهی‌ها) جواب می‌دهد
- می‌تواند پاسخ‌ها را **با صدا بخواند** (کلید بلندگو داخل پنل)
- فعال‌سازی: تنظیمات ← «دستیار هوشمند (Gemini)» ← کلید رایگان از aistudio.google.com/apikey — کلید فقط روی خود گوشی ذخیره می‌شود
- اگر قسطی نزدیک باشد، یک نشان قرمز روی خود گوی می‌بینید — خودش خبر می‌دهد

### 📅 اقساط و چک‌ها (تب جدید)
- تب جدید «اقساط و چک» کنار بدهی‌ها: ثبت قسط یا چک با عنوان، مبلغ، تاریخ سررسید جلالی، بانک/طرف حساب و حساب مرتبط
- **یادآور اعلان گوشی**: ۲ روز قبل سررسید (قابل تنظیم: روز سررسید تا ۱ هفته قبل + ساعت اعلان) برنامه از گوشی اجازه می‌گیرد و اعلان می‌دهد — حتی اگر برنامه بسته باشد
- **هشدار قرمز موجودی**: اگر موجودی حساب مرتبط کمتر از مبلغ قسط/چک باشد، همان کارت با هشدار قرمز «موجودی کافی نیست» نشان داده می‌شود (از تنظیمات قابل خاموش‌کردن)
- خلاصهٔ بالای تب: پرداخت‌نشده / سررسید گذشته / نزدیک سررسید + نوار نزدیک‌ترین سررسید
- دکمهٔ «پرداخت شد»: همزمان می‌تواند یک تراکنش هزینه در همان حساب ثبت کند؛ فیلترهای همه/پیش‌رو/گذشته/پرداخت‌شده و قسط/چک
- اقساط در پشتیبان‌گیری هم لحاظ می‌شوند

### 🏦 تفکیک مطمئن‌تر چند حساب از یک شماره
- اگر از یک بانک چند حساب دارید (یک شمارهٔ فرستنده)، حالا تطبیق با **امتیازدهی** انجام می‌شود: حسابی که بیشترین ارقام مشترک با شمارهٔ حساب/کارت داخل پیامک دارد برنده است — دیگر حساب اشتباه انتخاب نمی‌شود
- برای اینکه همیشه درست تفکیک شود، در فرم هر حساب، شماره حساب و شماره کارت را کامل وارد کنید

### 🛠 موارد دیگر
- فیکس فایل CI (trigger push روی main)
- مجموع تست‌های خودکار: ۴۰۵ مورد سبز

---
### 📲 نصب
فایل APK را دانلود و نصب کنید؛ روی نسخهٔ قبلی نصب می‌شود و داده‌های شما حفظ می‌شود. برای یادآور اعلان، بعد از نصب یک بار از تنظیمات «اجازه اعلان از گوشی» را بزنید.
EOF
)

RELEASE_ID=$(curl -s -H "Authorization: Bearer $TOKEN" "https://api.github.com/repos/$REPO/releases/tags/$TAG" | python3 -c "import sys,json;print(json.load(sys.stdin)['id'])")
echo "release id: $RELEASE_ID"

python3 - "$RELEASE_ID" "$BODY" <<'PY'
import json, sys, urllib.request
rid, body = sys.argv[1], sys.argv[2]
token = __import__("subprocess").check_output(
    ["bash", "-lc", "git config remote.origin.url | grep -oP '(?<=://)[^@]+(?=@)' | cut -d: -f2"],
    text=True).strip()
req = urllib.request.Request(
    f"https://api.github.com/repos/021hk/modiriat-hesab/releases/{rid}",
    data=json.dumps({"body": body}).encode(),
    headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
             "Content-Type": "application/json"},
    method="PATCH")
with urllib.request.urlopen(req) as r:
    print("PATCH status:", r.status)
PY
echo "done"

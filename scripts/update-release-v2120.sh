#!/usr/bin/env bash
# به‌روزرسانی توضیحات فارسی Release v2.12.0 — مدل شخص‌محور بدهی/طلب
set -euo pipefail

TAG="v2.12.0"
REPO="021hk/modiriat-hesab"
TOKEN=$(git config remote.origin.url | grep -oP '(?<=://)[^@]+(?=@)' | cut -d: -f2)

BODY=$(cat <<'EOF'
## حساب‌یار نسخه ۲.۱۲.۰ — بازسازی کامل بدهی/طلب (مدل شخص‌محور)

### ✳️ هر تراکنش فقط یک هویت دارد
- هر تراکنش فقط و فقط یکی از این‌ها ثبت می‌شود: **هزینه** | **درآمد** | **پرداخت بدهی** | **پرداخت قرض** | **دریافت طلب** | **دریافت بدهی**
- تراکنش‌های بدهی/طلب دیگر در آمار «هزینه/درآمد» حساب نمی‌شوند — دیگر هیچ عددی دوبار شمرده نمی‌شود
- در فرم تراکنش دو گزینه جدا دارید: «هزینه/درآمد» یا «بدهی یا طلب» (انتخاب انحصاری)

### 🎯 معیار طلب/بدهی = شخص + باقی‌مانده
- دیگر لازم نیست دستی انتخاب کنید طلب است یا بدهی؛ برنامه از **باقی‌ماندهٔ هر شخص** می‌فهمد:
  باقی‌مانده = مانده اولیه + گردش بدهی (پرداخت‌های شما به او) − گردش طلب (دریافت‌های شما از او)
- **مثبت → طلب دارید** | **منفی → بدهی دارید** | **صفر → تسویه شده**

### 🧾 عنوان خودکار تراکنش‌ها
- برداشت (خروج پول) → «پرداخت بدهی» (اگر به او بدهکارید) یا «پرداخت قرض» (قرض دادن به او)
- واریز (ورود پول) → «دریافت طلب» (اگر او به شما بدهکار است) یا «دریافت بدهی» (قرض گرفتن از او)
- تشخیص کاملاً خودکار از وضعیت فعلی شخص؛ در صورت نیاز «تشخیص دستی» هم هست

### 👤 کارت هر شخص — مثل دفتر
۱) **نام شخص** ۲) **گردش بدهی** و **گردش طلب** ۳) **وضعیت نهایی** (طلب دارید یا بدهی دارید — با مبلغ)
- «ریز جزئیات»: چقد پرداخت شده و چقد برداشت شده (با تعداد) + فهرست تراکنش‌های همان شخص با تاریخ

### 🔄 مهاجرت خودکار داده‌های قبلی
- بدهی‌ها/طلب‌های دستی قبلی به «مانده اولیه» همان شخص تبدیل می‌شوند (بدون دوبارشماری تراکنش‌ها)
- رکوردهای تکراری هم‌نام یک شخص می‌شوند؛ هیچ داده‌ای از بین نمی‌رود

### ➕ امکانات دیگر
- **اتصال خودکار شخص**: اگر نام شخص داخل پیامک بانک باشد، تراکنش خودکار به همان شخص وصل می‌شود
- فیلتر جدید «بدهی/طلب» در لیست تراکنش‌ها
- ثبت سریع پرداخت/دریافت برای هر شخص از منوی کارت او
- دکمه «شخص جدید» با مانده اولیه (طلب اولیه یا بدهی اولیه)
- حذف اتصال تراکنش از شخص → به هزینه/درآمد ساده برمی‌گردد

---
### 📲 نصب
فایل APK را دانلود و نصب کنید. اگر نسخهٔ قبلی را دارید، همین فایل روی آن نصب می‌شود و داده‌های شما حفظ می‌شود و خودکار به مدل جدید منتقل می‌شود.
EOF
)

RELEASE_ID=$(curl -s -H "Authorization: Bearer $TOKEN" "https://api.github.com/repos/$REPO/releases/tags/$TAG" | python3 -c "import sys,json;print(json.load(sys.stdin)['id'])")
echo "release id: $RELEASE_ID"

python3 - "$RELEASE_ID" "$BODY" <<'PY'
import json, sys, urllib.request
rid, body = sys.argv[1], sys.argv[2]
token = __import__("subprocess").check_output(
    ["git", "config", "remote.origin.url"], text=True
)
token = token.strip().split("//")[1].split("@")[0].split(":")[1]
req = urllib.request.Request(
    f"https://api.github.com/repos/021hk/modiriat-hesab/releases/{rid}",
    data=json.dumps({"body": body}).encode(),
    headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
    method="PATCH",
)
print(urllib.request.urlopen(req).status)
PY

#!/usr/bin/env bash
# به‌روزرسانی توضیحات فارسی Release v2.14.3 — سرعت Gemini + تم‌های رنگی + کهکشان + چت چسبان
set -euo pipefail

TAG="v2.14.3"
REPO="021hk/modiriat-hesab"
TOKEN=$(git config remote.origin.url | grep -oP '(?<=://)[^@]+(?=@)' | cut -d: -f2)

BODY=$(cat <<'EOF'
## حساب‌یار نسخه ۲.۱۴.۳ — دستیار سریع‌تر و پایدارتر + تم‌های رنگی (از جمله تم کهکشان ⭐)

### ⚡ رفع کندی و قطعی دستیار هوشمند (Gemini)
- **علت اصلی کندی پیدا و رفع شد**: مدل‌های ۲.۵ گوگل حالت «تفکر» پیش‌فرض دارند که هر پاسخ را ۱۰ تا ۳۰ ثانیه طولانی می‌کرد — برنامه حالا آن را خاموش می‌کند؛ پاسخ‌ها معمولاً در چند ثانیه می‌آیند
- **اتصال‌های ناپایدار (VPN) دیگر وسط کار قطع نمی‌شوند**: هر درخواست ۳ بار به‌طور خودکار دوباره امتحان می‌شود (با تایم‌اوت ۴۰ ثانیه‌ای برای هر تلاش) — پیام «سرور در دسترس نیست» فقط وقتی می‌آید که واقعاً هر ۳ تلاش ناموفق باشد
- پیام‌های خطای فارسی دقیق‌تر شدند: تایم‌اوت / اینترنت و VPN / کلید / سقف درخواست — هر کدام جدا

### 🎨 تم و رنگ‌بندی (جدید در تنظیمات)
- بخش «تم و رنگ‌بندی» به تنظیمات اضافه شد:
  - **رنگ اصلی برنامه**: سبز (پیش‌فرض)، بنفش، آبی، آسمانی، زرد — با انتخاب، همهٔ دکمه‌ها، هدرها و نمودارها هم‌رنگ می‌شوند
  - **تم مشکی کامل**: پس‌زمینهٔ کاملاً سیاه برای نمایشگرهای OLED
  - **تم کهکشانی ⭐**: پس‌زمینهٔ فضایی با **۱۳۰ ستارهٔ ریز چشمک‌زن**، دو سحابی شناور و شهاب گاه‌به‌گاه — ستاره‌ها به رنگ تم شما درمی‌آیند
- تم انتخابی بعد از بستن و بازکردن برنامه هم می‌ماند و گوی هوشمند هم از رنگ تم پیروی می‌کند

### 💬 پنجرهٔ گفتگوی دستیار
- **چسبیدن به گوی**: پنجرهٔ چت همیشه به گوی هوشمند می‌چسبد و دیگر فاصله نمی‌گیرد — وقتی کیبورد گوشی باز می‌شود، گوی بالا می‌آید و پنل با آن می‌ماند
- **تغییر اندازه**: با دستگیرهٔ گوشهٔ پنجره کوچک/بزرگش کنید، یا از دکمهٔ بزرگ‌کردن در هدر استفاده کنید — اندازه به‌خاطر سپرده می‌شود
- **پرش به پایین**: اگر در حرف‌های قبلی بالا رفته باشید، دکمهٔ ↓ ظاهر می‌شود و با یک لمس به آخرین پیام می‌برَدتان

### 🏦 اقساط
- **«حذف کامل طرح»**: حالا می‌توانید کل طرح قسط‌بندی — حتی اقساط پرداخت‌شده — را یک‌جا پاک کنید (با پیام تأیید). «حذف باقی‌ماندهٔ طرح» هم مثل قبل فقط اقساط پرداخت‌نشده را حذف می‌کند

### 🛠 موارد دیگر
- مجموع تست‌های خودکار: ۵۰۳ مورد سبز (۱۳ مجموعه)

---
### 📲 نصب
فایل APK را دانلود و روی نسخهٔ قبل نصب کنید؛ داده‌ها حفظ می‌شود.
EOF
)

RELEASE_ID=$(curl -s -H "Authorization: Bearer $TOKEN" "https://api.github.com/repos/$REPO/releases/tags/$TAG" | python3 -c "import sys,json;print(json.load(sys.stdin)['id'])")

curl -s -X PATCH \
  -H "Authorization: Bearer $TOKEN" \
  -H "Content-Type: application/json" \
  -d "$(python3 -c "import json,sys;print(json.dumps({'body': sys.stdin.read()}))" <<< "$BODY")" \
  "https://api.github.com/repos/$REPO/releases/$RELEASE_ID" > /dev/null

echo "release notes v2.14.3 updated (release id $RELEASE_ID)"
